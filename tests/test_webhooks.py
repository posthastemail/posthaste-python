def test_parse_returns_the_event_when_the_signature_holds() -> None:
    fixture = BY_NAME["delivered"]
    event = parse_webhook_event(
        fixture["body"], fixture["header"], fixture["secret"], now_seconds=fixture["timestamp"]
    )
    assert event is not None
    assert event["type"] == "delivered"
    assert event["data"]["messageId"] == "msg_AZLm3kQ8T2Sf9pXbNc7HrQ"


def test_parse_returns_none_on_a_bad_signature() -> None:
    fixture = BY_NAME["wrong_secret"]
    assert (
        parse_webhook_event(
            fixture["body"], fixture["header"], fixture["secret"], now_seconds=fixture["timestamp"]
        )
        is None
    )


def test_parse_returns_none_when_a_valid_signature_covers_non_json() -> None:
    fixture = BY_NAME["empty_body"]
    assert verify_webhook(
        fixture["body"], fixture["header"], fixture["secret"], now_seconds=fixture["timestamp"]
    ).valid
    assert (
        parse_webhook_event(
            fixture["body"], fixture["header"], fixture["secret"], now_seconds=fixture["timestamp"]
        )
        is None
    )


def test_header_names_are_exported_lower_cased() -> None:
    assert SIGNATURE_HEADER == "posthaste-signature"
    assert DELIVERY_ID_HEADER == "posthaste-delivery-id"
    assert ATTEMPT_HEADER == "posthaste-attempt"
