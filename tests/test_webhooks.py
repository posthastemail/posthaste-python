def test_rejects_a_stale_timestamp() -> None:
    fixture = BY_NAME["delivered"]
    result = verify_webhook(
        fixture["body"],
        fixture["header"],
        fixture["secret"],
        now_seconds=fixture["timestamp"] + 301,
    )
    assert result.reason == "timestamp_too_old"


def test_accepts_right_up_to_the_tolerance() -> None:
    fixture = BY_NAME["delivered"]
    assert verify_webhook(
        fixture["body"],
        fixture["header"],
        fixture["secret"],
        now_seconds=fixture["timestamp"] + 300,
    ).valid


def test_rejects_a_future_timestamp_by_the_same_tolerance() -> None:
    """Not clock skew to be generous about — an unlimited replay window."""
    fixture = BY_NAME["delivered"]
    result = verify_webhook(
        fixture["body"],
        fixture["header"],
        fixture["secret"],
        now_seconds=fixture["timestamp"] - 301,
    )
    assert result.reason == "timestamp_in_future"


def test_tolerance_is_configurable() -> None:
    fixture = BY_NAME["delivered"]
    assert verify_webhook(
        fixture["body"],
        fixture["header"],
        fixture["secret"],
        tolerance_seconds=3600,
        now_seconds=fixture["timestamp"] + 3000,
    ).valid


