@pytest.mark.parametrize(
    ("header", "reason"),
    [
        (None, "malformed_header"),
        ("", "malformed_header"),
        ("nonsense", "malformed_header"),
        ("t=notanumber,v1=abc", "malformed_header"),
        ("v1=abc", "malformed_header"),
        ("t=1760000000", "malformed_header"),
    ],
)
def test_malformed_headers(header: object, reason: str) -> None:
    assert (
        verify_webhook("{}", header, "whsec_example_secret_x", now_seconds=1760000000).reason  # type: ignore[arg-type]
        == reason
    )


def test_a_timestamp_with_only_a_newer_version_is_reported_as_such() -> None:
    """`v1=` is a version tag so a `v2=` can be added beside it.

    A header carrying only `v2` is not malformed — it is a scheme this SDK does
    not implement, and telling those two apart is the difference between "fix
    your header" and "upgrade your SDK".
    """
    result = verify_webhook(
        "{}", "t=1760000000,v2=deadbeef", "whsec_example_secret_x", now_seconds=1760000000
    )
    assert result.reason == "unsupported_version"


def test_the_header_is_parsed_by_key_not_by_position() -> None:
    """A future `v2=` inserted BEFORE `v1=` must not shift what gets compared."""
    fixture = BY_NAME["delivered"]
    stamp, v1 = fixture["header"].split(",")
    reordered = f"{stamp},v2=0000,{v1}"
    assert verify_webhook(
        fixture["body"], reordered, fixture["secret"], now_seconds=fixture["timestamp"]
    ).valid


def test_a_non_ascii_signature_is_rejected_not_crashed() -> None:
    """`hmac.compare_digest` raises TypeError on a non-ASCII `str`.

    The value is attacker-controlled, so comparing the strings directly would
    turn a forged signature into a 500 inside the customer's handler instead of
    a clean rejection.
    """
    result = verify_webhook(
        "{}", "t=1760000000,v1=café", "whsec_example_secret_x", now_seconds=1760000000
    )
    assert result.reason == "signature_mismatch"


def test_an_empty_secret_fails_closed() -> None:
    fixture = BY_NAME["delivered"]
    assert (
        verify_webhook(fixture["body"], fixture["header"], "", now_seconds=fixture["timestamp"]).reason
        == "signature_mismatch"
    )


